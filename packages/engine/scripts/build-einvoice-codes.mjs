/**
 * Writes src/lib/einvoice/codes.generated.ts from the code database of a Factur-X release
 * (`FACTUR-X_EN16931_codedb.xml`, shipped beside the schematron of the same release).
 *
 *   node packages/engine/scripts/build-einvoice-codes.mjs <path or URL of the codedb.xml>
 *
 * The lists are the ones the validator in the e-invoice sidecar checks against, so a code refused
 * there is refused when the request arrives, with the field's name. Run it again when the sidecar
 * moves to another release (apps/conformance/versions.json) and commit the result.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) {
  console.error(
    'usage: build-einvoice-codes.mjs <path or URL of FACTUR-X_EN16931_codedb.xml>',
  );
  process.exit(2);
}
const xml = /^https?:/.test(source)
  ? await (await fetch(source)).text()
  : readFileSync(source, 'utf8');

/** The lists by the number the schematron knows them under, and what each one is checked on. */
const wanted = [
  ['2', 'documentTypeCodes', 'Invoice type code (BT-3), UNTDID 1001'],
  [
    '7',
    'countryCodes',
    'Country codes (BT-40, BT-55, BT-80), ISO 3166-1 alpha-2',
  ],
  [
    '8',
    'unitCodes',
    'Units of measure (BT-130, BT-150), UN/ECE Recommendation 20 with 21',
  ],
  [
    '17',
    'electronicAddressSchemes',
    'Electronic address schemes (BT-34, BT-49), the EAS list',
  ],
  ['24', 'currencyCodes', 'Currencies (BT-5, BT-6), ISO 4217'],
  ['25', 'paymentMeansCodes', 'Payment means (BT-81), UNTDID 4461'],
];

const release = /Version:\s*([0-9.]+)/.exec(xml)?.[1];
if (!release)
  throw new Error('The file names no Factur-X release; is it a codedb.xml?');

const lists = new Map();
for (const match of xml.matchAll(/<cl id="(\d+)">([\s\S]*?)<\/cl>/g))
  lists.set(
    match[1],
    [...match[2].matchAll(/value="([^"]*)"/g)].map((value) => value[1]),
  );

/** One long string would be a 9 kB line; this keeps the file readable in a diff. */
function literal(codes) {
  const lines = [];
  let line = '';
  for (const code of codes) {
    if (line && line.length + code.length + 1 > 88) {
      lines.push(line);
      line = '';
    }
    line += (line ? ' ' : '') + code;
  }
  if (line) lines.push(line);
  return lines
    .map((text, index) => `    '${text}${index < lines.length - 1 ? ' ' : ''}'`)
    .join(' +\n');
}

let out = `// Generated by packages/engine/scripts/build-einvoice-codes.mjs from the code database of
// Factur-X ${release}. Do not edit: run the script again when the sidecar moves to another release.

const list = (codes: string): ReadonlySet<string> => new Set(codes.split(' '));

/** The Factur-X release these lists were taken from. */
export const CODE_LIST_RELEASE = '${release}';
`;
for (const [id, name, description] of wanted) {
  const codes = lists.get(id);
  if (!codes?.length)
    throw new Error(`Code list ${id} (${name}) is missing from the file`);
  if (codes.some((code) => /[\s'\\]/.test(code)))
    throw new Error(
      `Code list ${id} holds a code that cannot be written as it is`,
    );
  out += `\n/** ${description}. ${codes.length} codes. */\nexport const ${name} = list(\n${literal(codes)},\n);\n`;
}

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'lib',
  'einvoice',
  'codes.generated.ts',
);
// written the way Prettier leaves it, or every regeneration would fail the format check
const prettier = await import('prettier');
writeFileSync(
  target,
  await prettier.format(out, {
    ...(await prettier.resolveConfig(target)),
    filepath: target,
  }),
);
console.log(
  `Factur-X ${release}: ${wanted.map(([id, name]) => `${name} ${lists.get(id).length}`).join(', ')}`,
);
